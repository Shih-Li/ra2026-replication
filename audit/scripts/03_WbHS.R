  "sd_rosen1",
  rhs_vars
)


analysis_sample <- analysis_all[
  stats::complete.cases(
    analysis_all[
      ,
      model_vars,
      drop = FALSE
    ]
  ),
  ,
  drop = FALSE
]


row.names(analysis_sample) <- NULL


if (anyNA(analysis_sample$ID_Participante)) {
  
  stop(
    "`ID_Participante` contains missing values in the estimation sample.",
    call. = FALSE
  )
}


