# ------------------------------------------------------------------------------
# 16. Original-estimator function for EXACT REFITS
# ------------------------------------------------------------------------------

paper_refit <- function(
    data,
    spec
) {
  
  # Exact Paper 3 point-estimator refit.
  #
  # The original reporting step applies HC1 covariance to this lm object,
  # but HC1 does not change coef(fit)["treatment"].
  stats::lm(
    formula = original_formula,
    data = data,
    na.action = stats::na.fail
  )
}


