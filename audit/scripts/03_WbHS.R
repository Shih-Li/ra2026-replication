)


# ------------------------------------------------------------------------------
# 11. ORIGINAL REPLICATION
# ------------------------------------------------------------------------------

# The supplied replication fits this model using OLS and calculates HC1 robust
# standard errors afterward.
#
# HC1 affects inference, but does not change the OLS treatment slope.
original_fit <- stats::lm(
  formula = original_formula,
  data = analysis_sample,
  na.action = stats::na.fail
)


N_original <- as.integer(
  stats::nobs(original_fit)
)


original_coef <- stats::coef(
  original_fit
)


if (!TARGET %in% names(original_coef)) {
  
  stop(
    paste0(
      "Target coefficient `",
      TARGET,
      "` is absent from original_fit."
    ),
    call. = FALSE
  )
}


beta_original <- unname(
  original_coef[[TARGET]]
)


if (
  length(beta_original) != 1L ||
  !is.finite(beta_original)
) {
  
  stop(
    "Could not recover a finite Paper 3 treatment coefficient.",
    call. = FALSE
  )
}


# ------------------------------------------------------------------------------
# 12. Validate ORIGINAL REPLICATION
# ------------------------------------------------------------------------------

if (N_original != EXPECTED_N) {
  
  stop(
    paste0(
      "\n",
      "Folder:\n",
      "    audit/scripts/\n\n",
      
      "File:\n",
      "    03_WbHS.R\n\n",
      
      "Problem:\n",
      "    Original Paper 3 estimator does not reproduce expected N.\n\n",
      
      "Expected:\n",
      "    N = ", EXPECTED_N, "\n",
      "    beta = ",
      format(
        EXPECTED_BETA,
        digits = 16
      ),
      "\n\n",
      
      "Obtained:\n",
      "    N = ", N_original, "\n",
      "    beta = ",
      format(
        beta_original,
        digits = 16
      ),
      "\n\n",
      
      "Likely cause:\n",
      "    baseline/self-esteem controls, randomization strata, ",
      "missingness, or processed-data mismatch."
    ),
    call. = FALSE
  )
}


if (
  abs(
    beta_original -
    EXPECTED_BETA
  ) > BETA_TOLERANCE
) {
  
  stop(
    paste0(
      "\n",
      "Folder:\n",
      "    audit/scripts/\n\n",
      
      "File:\n",
      "    03_WbHS.R\n\n",
      
      "Problem:\n",
      "    Original Paper 3 estimator does not reproduce the retained ",
      "Table 5 treatment coefficient.\n\n",
      
      "Expected:\n",
      "    N = ", EXPECTED_N, "\n",
      "    beta = ",
      format(
        EXPECTED_BETA,
        digits = 16
      ),
      "\n\n",
      
      "Obtained:\n",
      "    N = ", N_original, "\n",
      "    beta = ",
      format(
        beta_original,
        digits = 16
      ),
      "\n",
      
      "    absolute difference = ",
      format(
        abs(
          beta_original -
            EXPECTED_BETA
