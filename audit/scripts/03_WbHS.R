# ------------------------------------------------------------------------------
# 9. Define the exact published regression
# ------------------------------------------------------------------------------

# Paper 3 Table 5, first follow-up, self-esteem, full sample.
#
# main_outcome_block():
#
#   outcome  = sd_rosen1
#   baseline = sd_rosen0
#   controls = controls_unb()
#
# controls_unb():
#
#   lb_years_education
#   lb_jefe_hogar
#
# outcome_result() additionally includes the randomization-strata indicators.
rhs_vars <- c(
  TARGET,
  "sd_rosen0",
  "lb_years_education",
  "lb_jefe_hogar",
  strata_vars
)


original_formula <- stats::reformulate(
  termlabels = rhs_vars,
  response = "sd_rosen1"
)


# ------------------------------------------------------------------------------
# 10. Freeze the exact estimation sample
# ------------------------------------------------------------------------------

